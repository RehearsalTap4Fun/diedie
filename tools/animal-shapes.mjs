// 34 个常见动物的手工轮廓（叠动物模式的「省份」）。
// 设计空间约 0-100（y 向下），点按顺时针；第三元素 1 = 尖角（Chaikin 平滑时保留）。
// face 为表情锚点（设计空间坐标，必须落在头部轮廓内）；er 为眼睛半径（设计单位，缺省 7）；
// px 为目标最大边长（对标省份 130-300 的分布，大动物大块、小动物小块）。

/** 生成椭圆弧点列（角度制，顺时针） */
function arc(cx, cy, rx, ry, a0, a1, n) {
  const pts = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return pts;
}

/** 花瓣/云朵边：绕椭圆一周交替内外半径（sharpOuter 时外点保留尖角不被平滑） */
function scallops(cx, cy, rx, ry, bumps, depth, a0 = 0, a1 = 360, sharpOuter = false) {
  const pts = [];
  const n = bumps * 2;
  for (let i = 0; i < n * ((a1 - a0) / 360); i++) {
    const a = ((a0 + ((a1 - a0) * i) / (n * ((a1 - a0) / 360))) * Math.PI) / 180;
    const outer = i % 2 === 0;
    const k = outer ? 1 + depth : 1;
    const p = [cx + rx * k * Math.cos(a), cy + ry * k * Math.sin(a)];
    if (outer && sharpOuter) p.push(1);
    pts.push(p);
  }
  return pts;
}

/** 右半轮廓沿 x=axis 镜像成整圈（右半从顶部中线开始、到底部中线结束，顺时针） */
function mirrored(rightHalf, axis = 50) {
  const left = [...rightHalf]
    .reverse()
    .map(([x, y, s]) => (s ? [2 * axis - x, y, s] : [2 * axis - x, y]));
  return [...rightHalf, ...left];
}

